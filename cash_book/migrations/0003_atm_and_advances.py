"""
The card, the advances, and a real number for a bunch.

Three things arrive together because they are one story: where the cash comes
from, who is holding it before it is explained, and how the batches of vouchers
are identified.

RENUMBERING THE BUNCHES
-----------------------
The spreadsheet's "Bunch" column was never an identifier. It is the *total* of
the vouchers in the batch -- all 45 of them sum exactly to their own number,
the Send sheet prints each batch under "Total 17570", and the ATM sheet lists
the same figures as "Amount Submit". Importing it as the bunch's number made
the next bunch raised on a seeded book come out at 36973, and would have made
two batches of the same value indistinguishable.

So bunches are renumbered here, 1 upwards per company in the order they were
sent, and the total goes back to being what it always was: a sum, computed from
the entries, correct by construction as they are added or cancelled.
"""

