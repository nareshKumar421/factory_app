def renumber_bunches(apps, schema_editor):
    """Give every bunch a plain sequence number, per company, oldest first.

    The number it had was the batch total -- see the module docstring. It is
    not preserved anywhere because it is not lost: summing the bunch's entries
    returns it exactly.
    """
    CashBunch = apps.get_model("cash_book", "CashBunch")
    Company = apps.get_model("company", "Company")

    for company in Company.objects.all():
        bunches = list(
            CashBunch.objects.filter(company=company).order_by("sent_at", "id")
        )
        if not bunches:
            continue
        # Two passes: the unique constraint on (company, number) would trip on
        # the way past a number still held by a bunch further down the list.
        offset = max(bunch.number for bunch in bunches) + 1
        for index, bunch in enumerate(bunches):
            bunch.number = offset + index
            bunch.save(update_fields=["number"])
        for index, bunch in enumerate(bunches, start=1):
            bunch.number = index
            bunch.save(update_fields=["number"])


def unrenumber_bunches(apps, schema_editor):
    """Put each bunch's number back to the total of its entries.

    Which is what it was before, and is derivable, so reversing loses nothing.
    """
    CashBunch = apps.get_model("cash_book", "CashBunch")
    for bunch in CashBunch.objects.all():
        total = 0
        for entry in bunch.entries.filter(is_active=True):
            total += entry.amount if entry.direction == "OUT" else -entry.amount
        bunch.number = int(total)
        bunch.save(update_fields=["number"])


