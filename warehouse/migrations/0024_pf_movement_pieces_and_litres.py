"""Count movement lines in pieces, and carry SAP's litre factor.

Hand-written rather than autogenerated because ``boxes`` -> ``pieces`` is not a
rename: 12 boxes is not 12 pieces, and letting Django rename the column would
silently restate every filed declaration at a twentieth of its real quantity.

The conversions, and what each is worth:

* **Lines convert faithfully.** Each one stored ``pieces_per_box`` at the time it
  was typed, so ``pieces = boxes x pieces_per_box`` is exact. A line that never
  got a pack size from SAP keeps its number as-is — the only figure available —
  which is right for the ``SalFactor2 = 1`` items where a box IS the piece.
* **``litres_per_piece`` starts null on existing lines.** SAP was not asked for
  it when they were typed, and back-filling from today's item master would
  attach a factor the keeper never saw to a declaration he already made. Their
  litre column reads as unknown until the line is saved again, which is honest.
* **Event totals do NOT convert.** An event snapshots what the document said at
  one moment and stores no per-line pack sizes, so a box total cannot be turned
  into a piece total without inventing the factors. Historical events therefore
  carry 0 pieces; the trail still shows who changed what and when, and the live
  document beside it carries the real figures. Inventing a number there would be
  worse than admitting the gap.

On rolling back: ``pieces_to_boxes`` restores the column's contents, but the step
that re-creates ``boxes`` itself will fail on a populated table — the column is
NOT NULL with no database default, so Postgres refuses to add it back to rows
that already exist. The reverse is therefore usable on an empty table and loud
rather than silent on a full one, which is the right way round: a rollback that
half-succeeded would leave piece counts sitting in a column named ``boxes``.
"""

from django.db import migrations, models


def boxes_to_pieces(apps, schema_editor):
    """``pieces = boxes x pieces_per_box``, exactly, off each line's own snapshot."""
    Line = apps.get_model("warehouse", "PFStockMovementLine")
    for line in Line.objects.all().iterator():
        factor = line.pieces_per_box if (line.pieces_per_box or 0) >= 1 else 1
        Line.objects.filter(pk=line.pk).update(pieces=line.boxes * factor)


def pieces_to_boxes(apps, schema_editor):
    """The reverse, for a rollback. Lossy where the division does not come out.

    A part box cannot be expressed in the column being restored, so the
    remainder is dropped — which is exactly why the forward direction is the one
    that keeps the data whole.
    """
    Line = apps.get_model("warehouse", "PFStockMovementLine")
    for line in Line.objects.all().iterator():
        factor = line.pieces_per_box if (line.pieces_per_box or 0) >= 1 else 1
        Line.objects.filter(pk=line.pk).update(boxes=line.pieces // factor)


